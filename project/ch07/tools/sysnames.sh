#!/bin/sh
# sysnames.sh - write src/sysnames.h, the table of x86-64 system call
# names, from the kernel's header:
#
#     tools/sysnames.sh > src/sysnames.h
#
# Each line "#define __NR_write 1" becomes [1] = "write",.
H=${1:-/usr/include/x86_64-linux-gnu/asm/unistd_64.h}
echo "/* sysnames.h - x86-64 system call names, generated by tools/sysnames.sh"
echo " * from $(basename "$H"). Do not edit. */"
echo "static const char *const sys_names[] = {"
awk '$1 == "#define" && $2 ~ /^__NR_/ { sub(/^__NR_/, "", $2); printf "    [%d] = \"%s\",\n", $3, $2 }' "$H"
echo "};"
